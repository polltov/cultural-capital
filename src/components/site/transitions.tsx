import { ViewTransition } from "react";

/*
 * Переходы между страницами (React <ViewTransition> поверх View Transitions API браузера).
 * Каждый переход что-то сообщает, иначе его нет:
 *
 * | Откуда → куда                                   | Типы ссылки         | Что видно                                  |
 * |-------------------------------------------------|---------------------|--------------------------------------------|
 * | каталог на главной → страница экскурсии          | OPEN_TOUR           | обложка карточки перетекает в обложку      |
 * |                                                 |                     | страницы, остальное сдвигается влево       |
 * | первый экран, афиша, новости → экскурсия/новость | NAV_FORWARD         | страница сдвигается влево («глубже»)       |
 * | «Экскурсии», «Весь каталог» со страницы экскурсии| BACK_TO_CATALOG     | обложка возвращается в свою карточку,      |
 * |                                                 |                     | страница сдвигается вправо                 |
 * | хлебные крошки, «← Все новости»                  | NAV_BACK            | страница сдвигается вправо («назад»)       |
 * | меню, подвал, «Другие экскурсии», кнопка «Назад» | —                   | мягкая смена за 250 мс без сдвига: это не  |
 * |                                                 |                     | движение по иерархии                       |
 *
 * Классы анимаций и закреплённая шапка — в site.css, раздел «Переходы между страницами».
 * В браузере без поддержки View Transitions страницы просто сменяются, как раньше.
 */

export const NAV_FORWARD = ["nav-forward"];
export const NAV_BACK = ["nav-back"];
/** Из каталога в экскурсию: вглубь, и обложка карточки становится обложкой страницы. */
export const OPEN_TOUR = ["nav-forward", "tour-cover"];
/** Со страницы экскурсии к каталогу: назад, и обложка возвращается в карточку. */
export const BACK_TO_CATALOG = ["nav-back", "tour-cover"];

const DIRECTIONAL = { "nav-forward": "nav-forward", "nav-back": "nav-back", default: "none" } as const;

/**
 * Обёртка всей страницы: сдвиг по направлению перехода. Стоит снаружи всех DOM-узлов страницы (в SiteShell),
 * иначе React не запустит enter/exit; в layout её ставить нельзя — layout не размонтируется при переходах.
 * Переходы без типа (меню, «Назад» браузера) страницу не сдвигают: `default: "none"`, остаётся только
 * стандартная смена кадра браузером. Обновление данных на той же странице (опрос оплаты, router.refresh)
 * перехода не запускает вовсе.
 */
export function PageTransition({ children }: { children: React.ReactNode }) {
  return (
    <ViewTransition enter={DIRECTIONAL} exit={DIRECTIONAL} default="none">
      {children}
    </ViewTransition>
  );
}

/**
 * Обложка экскурсии, которая перетекает между карточкой каталога и страницей экскурсии. Имя одно на экскурсию,
 * поэтому на странице может быть только одна такая обложка (на странице экскурсии карточки «Другие экскурсии»
 * её не получают). Перетекание включается только типом `tour-cover`: кнопка «Назад» браузера и ссылки из афиши
 * не тянут обложку из-за края экрана, где карточка может оказаться после прокрутки.
 */
export function TourCoverTransition({ slug, children }: { slug: string; children: React.ReactNode }) {
  return (
    <ViewTransition name={`tour-cover-${slug}`} share={{ "tour-cover": "morph", default: "none" }} default="none">
      {children}
    </ViewTransition>
  );
}
