// Реквизиты оператора персональных данных и исполнителя услуг.
// Заполняет владелец сайта. Пустые поля в подвале не показываются,
// а в документах выводятся как «[не заполнено]» — так их видно до публикации.

export const operator = {
  /** Например: «Индивидуальный предприниматель Иванова Мария Сергеевна» или «ООО „Культурная Столица“». */
  name: "",
  /** ИНН. */
  inn: "",
  /** ОГРН (для ООО) или ОГРНИП (для ИП). Самозанятым не нужен. */
  ogrn: "",
  /** Почтовый адрес для обращений субъектов персональных данных. */
  address: "",
  email: "",
  phone: "",
};

/** Дата, с которой действуют текущие редакции политики и согласия. */
export const LEGAL_EDITION = "7 октября 2026 г.";

export const MISSING = "[не заполнено]";

export const or = (v: string) => v.trim() || MISSING;

export function ogrnLabel(name: string): string {
  return /индивидуальн|^ип\b/i.test(name) ? "ОГРНИП" : "ОГРН";
}
