import { revalidatePath } from "next/cache";

/**
 * Сбрасывает кэш всего публичного сайта. Экскурсии, даты и свободные места показывают сразу несколько страниц
 * (главная, афиша, страницы экскурсий, карта сайта), поэтому вместо перечисления путей сбрасываем корневой layout:
 * страницы перестроятся при следующем визите. Сайт маленький, лишней работы почти нет, а забыть страницу нельзя.
 */
export function revalidatePublicSite(): void {
  revalidatePath("/", "layout");
}
